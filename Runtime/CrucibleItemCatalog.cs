    public static IReadOnlyList<CrucibleItem> Items { get; } =
        AllItems.Where(x => x.Id is >= 76 and <= 143).ToArray();

    public static string GetName(uint itemId)
        => AllItems.FirstOrDefault(x => x.Id == itemId)?.Name ?? $"未知斗兽奇弈物品 {itemId}";

    public static string GetCategory(uint itemId)
        => itemId switch
        {
            < 76 => "斗兽装备",
            <= 143 => "奇弈道具",
            _ => "食料",
        };

    public static bool IsElementalAxe(uint itemId)
        => ElementalAxeIds.Contains(itemId);

    public static bool HasElementalAxe(IEnumerable<uint> itemIds)
        => itemIds.Any(IsElementalAxe);
